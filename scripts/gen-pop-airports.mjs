// Writes lib/signals/pop-airports.data.ts: IATA code -> [city, ISO2, lat, lon].
//
// CDN and cloud vendors name their points of presence by airport code: Cloudflare's
// status components end "(SYD)", Fastly's titles read "Toronto (YYZ)". The
// cloud-status layer uses this table to pin an incident at the PoP it names instead
// of at the vendor's head office. Rows come from OurAirports (public domain): every
// large airport with an IATA code, plus every airport whose code Cloudflare lists as
// a PoP today (Cloudflare has PoPs in cities with only a medium or small airport).
// The coordinate is the airport's: a mark for the metro area, not the data centre.
//
//   node scripts/gen-pop-airports.mjs
//
// Two requests: OurAirports' CSV (about 12 MB) and Cloudflare's components.json.

import { writeFileSync } from "node:fs";

const AIRPORTS = "https://davidmegginson.github.io/ourairports-data/airports.csv";
const CF_COMPONENTS = "https://www.cloudflarestatus.com/api/v2/components.json";
const OUT = new URL("../lib/signals/pop-airports.data.ts", import.meta.url);
const UA = { "User-Agent": "Provenance/1.0 (+provenance-online.com)" };

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else q = false;
      } else field += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (ch !== "\r") field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const [csvText, cf] = await Promise.all([
  fetch(AIRPORTS, { headers: UA }).then((r) => { if (!r.ok) throw new Error(`airports ${r.status}`); return r.text(); }),
  fetch(CF_COMPONENTS, { headers: UA }).then((r) => { if (!r.ok) throw new Error(`cloudflare ${r.status}`); return r.json(); }),
]);

const cfCodes = new Set();
for (const c of cf.components ?? []) {
  const m = /\(([A-Z]{3})\)\s*$/.exec(c.name ?? "");
  if (m) cfCodes.add(m[1]);
}

const [head, ...rows] = parseCsv(csvText);
const col = (n) => head.indexOf(n);
const I = { type: col("type"), lat: col("latitude_deg"), lon: col("longitude_deg"), cc: col("iso_country"), city: col("municipality"), iata: col("iata_code"), sched: col("scheduled_service") };

// Prefer the airport with scheduled service when a code appears twice.
const byCode = new Map();
for (const r of rows) {
  const code = (r[I.iata] ?? "").trim().toUpperCase();
  if (!/^[A-Z]{3}$/.test(code)) continue;
  const type = r[I.type];
  if (type !== "large_airport" && !cfCodes.has(code)) continue;
  if (type === "closed") continue;
  const lat = Number(r[I.lat]), lon = Number(r[I.lon]);
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  const prev = byCode.get(code);
  const sched = r[I.sched] === "yes";
  if (prev && (prev.sched || !sched)) continue;
  byCode.set(code, { city: (r[I.city] ?? "").trim(), cc: (r[I.cc] ?? "").trim().toUpperCase(), lat, lon, sched });
}

const codes = [...byCode.keys()].sort();
const missing = [...cfCodes].filter((c) => !byCode.has(c)).sort();
const lines = codes.map((c) => {
  const a = byCode.get(c);
  return `  ${c}: [${JSON.stringify(a.city)}, "${a.cc}", ${Math.round(a.lat * 100) / 100}, ${Math.round(a.lon * 100) / 100}],`;
});

const src = `// GENERATED by scripts/gen-pop-airports.mjs from OurAirports (public domain): every
// large airport with an IATA code, plus the airports behind Cloudflare's PoP codes.
// Do not hand-edit: run the script. ${codes.length} codes.
// Cloudflare PoP codes with no airport row (closed or not an airport code): ${missing.join(", ") || "none"}.
//
// IATA code -> [city, ISO 3166-1 alpha-2, lat, lon]. The airport's coordinate: a mark
// for the metro area a PoP serves, not the data centre.

export type PopAirportRow = readonly [city: string, iso2: string, lat: number, lon: number];

export const POP_AIRPORTS: Readonly<Record<string, PopAirportRow>> = {
${lines.join("\n")}
};

/** The row for a three-letter IATA code, or undefined. */
export function popAirport(code: string): PopAirportRow | undefined {
  return Object.prototype.hasOwnProperty.call(POP_AIRPORTS, code) ? POP_AIRPORTS[code] : undefined;
}
`;
writeFileSync(OUT, src);
console.log(`wrote ${codes.length} codes; cloudflare codes with no row: ${missing.length}`);
