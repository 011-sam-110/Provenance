// Writes lib/eye/planeTypes.data.ts: every type code the plane pull asks for, the model it is drawn
// with and its own length. Run after fetch-dimensions.mjs or after editing shapes.json:
//
//   node scripts/plane-models/gen-types.mjs
//
// A code with no published length takes its model's, and the generated row is marked `borrowed`,
// so the table never states a measured length it does not hold.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "../../lib/eye/planeTypes.data.ts");
const { models, closest } = JSON.parse(readFileSync(join(HERE, "shapes.json"), "utf8"));
const dims = JSON.parse(readFileSync(join(HERE, "dimensions.json"), "utf8"));

/** A row's figures: EUROCONTROL's, then any person's correction with its own source. */
const figures = (code) => ({ ...(dims[code] ?? {}), ...(dims[code]?.override ?? {}) });

const lines = [];
for (const code of Object.keys(dims).sort()) {
  const model = models[code] ? code : closest[code];
  if (!model) throw new Error(`${code} has no model and no closest model in shapes.json`);
  const own = figures(code).lengthM;
  const length = own ?? figures(model).lengthM;
  if (!length) throw new Error(`${model} has no length`);
  lines.push(`  ${code}: { model: ${JSON.stringify(model)}, lengthM: ${length}${own ? "" : ", borrowed: true"} },`);
}

writeFileSync(
  OUT,
  `// GENERATED by scripts/plane-models/gen-types.mjs. Do not edit by hand.
// Every ICAO type code the plane pull asks for: the model it is drawn with, and its own length in
// metres from scripts/plane-models/dimensions.json. \`borrowed\` means no published length was
// found for this code, so it takes its model's.

export interface PlaneTypeRow {
  model: string;
  lengthM: number;
  borrowed?: true;
}

export const PLANE_TYPES: Readonly<Record<string, PlaneTypeRow>> = {
${lines.join("\n")}
};

export const PLANE_MODEL_IDS: readonly string[] = ${JSON.stringify(Object.keys(models).sort())};
`,
);
console.log(`${lines.length} codes, ${Object.keys(models).length} models`);
