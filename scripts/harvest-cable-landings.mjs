#!/usr/bin/env node
// Re-harvest lib/signals/cable-landings.osm.data.ts: every OpenStreetMap
// `telecom=cable_landing_station`, read from QLever's OSM-planet index. The cable
// landings layer uses it to move TeleGeography's town-level landing pins onto the
// station building where OSM maps one (lib/signals/cable-stations.ts).
//
//   node scripts/harvest-cable-landings.mjs            write the file
//   node scripts/harvest-cable-landings.mjs --dry-run  print counts only
//
// A snapshot, not a live read: Overpass refused or failed 5 of 10 calls during the
// 2026-10-16 audit and QLever takes ~50 s for this query, while the set changes a
// few times a year. Writes NOTHING when the read fails or looks truncated.
import { writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const UA = "TrafficNerd/2.0 (+github.com/011-sam-110/TrafficNerd-V2)";
const QLEVER = "https://qlever.dev/api/osm-planet";
const OUT = "lib/signals/cable-landings.osm.data.ts";
const PLAUSIBLE_MIN = 40; // 58 on 2026-10-16

const QUERY = `PREFIX osmkey: <https://www.openstreetmap.org/wiki/Key:>
PREFIX geo: <http://www.opengis.net/ont/geosparql#>
PREFIX geof: <http://www.opengis.net/def/function/geosparql/>
SELECT ?osm ?name ?operator ?centroid WHERE {
  ?osm osmkey:telecom "cable_landing_station" .
  ?osm geo:hasGeometry/geo:asWKT ?g .
  BIND (geof:centroid(?g) AS ?centroid)
  OPTIONAL { ?osm osmkey:name ?name }
  OPTIONAL { ?osm osmkey:operator ?operator }
}`;

async function sparql(query, timeoutMs) {
  try {
    const res = await fetch(QLEVER, {
      method: "POST",
      headers: { Accept: "application/sparql-results+json", "Content-Type": "application/x-www-form-urlencoded", "User-Agent": UA },
      body: `query=${encodeURIComponent(query)}`,
      signal: AbortSignal.timeout(timeoutMs),
    });
    if (!res.ok) throw new Error(`QLever answered ${res.status}`);
    return (await res.json()).results.bindings;
  } catch (err) {
    // Some networks drop the first SYNs to qlever.dev, so the TCP connect takes ~20 s
    // and undici gives up at its fixed 10 s connect timeout. curl waits longer.
    console.warn(`QLever: ${err.cause?.code ?? err.message}; retrying with curl`);
    const out = execFileSync(
      "curl",
      ["-sS", "--fail", "--max-time", String(Math.ceil(timeoutMs / 1000)), "-A", UA,
       "-H", "Accept: application/sparql-results+json", "--data-urlencode", `query=${query}`, QLEVER],
      { maxBuffer: 16 * 1024 * 1024 },
    );
    return JSON.parse(out.toString("utf8")).results.bindings;
  }
}

const round = (n) => Math.round(n * 1e5) / 1e5;
const rows = [];
for (const b of await sparql(QUERY, 180_000)) {
  const v = (k) => b[k]?.value?.trim() ?? "";
  const m = v("osm").match(/openstreetmap\.org\/(node|way|relation)\/(\d+)$/);
  const p = v("centroid").match(/POINT\(\s*(-?[\d.]+)\s+(-?[\d.]+)\s*\)/);
  if (!m || !p) continue;
  rows.push({
    osm: `${m[1]}/${m[2]}`,
    ...(v("name") ? { name: v("name") } : {}),
    ...(v("operator") ? { operator: v("operator") } : {}),
    lat: round(Number(p[2])),
    lon: round(Number(p[1])),
  });
}
if (rows.length < PLAUSIBLE_MIN) {
  console.error(`QLever returned ${rows.length} stations (< ${PLAUSIBLE_MIN}); nothing written`);
  process.exit(1);
}
rows.sort((a, b) => a.osm.localeCompare(b.osm));
const today = new Date().toISOString().slice(0, 10);
console.log(`${rows.length} stations, ${rows.filter((r) => r.name).length} named`);
if (process.argv.includes("--dry-run")) process.exit(0);

writeFileSync(
  OUT,
  `// GENERATED by scripts/harvest-cable-landings.mjs — do not hand-edit. Every
// OpenStreetMap telecom=cable_landing_station, from QLever's OSM-planet index.
// OSM data © OpenStreetMap contributors, ODbL 1.0.
//
// Harvested: ${today} (UTC). Rows: ${rows.length} stations.

export interface OsmLandingStation {
  /** \`<type>/<id>\` as in the OSM URL. */
  osm: string;
  name?: string;
  operator?: string;
  lat: number;
  lon: number;
}

export const OSM_LANDING_STATIONS_DATE = "${today}";

export const OSM_LANDING_STATIONS: OsmLandingStation[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`,
);
console.log(`wrote ${OUT}`);
