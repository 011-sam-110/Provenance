// Writes lib/signals/ioda-regions.data.ts: IODA region id -> [name, ISO2, lat, lon].
//
// IODA names a sub-national outage as "region/<id>" and nothing else, so the
// internet-outages layer needs this join table to place one. The ids and the shapes
// come from IODA's own /v2/topo/region, which is Natural Earth admin-1 (public domain)
// with IODA's ids attached. The anchor is the area-weighted centroid of each region's
// LARGEST polygon, so an island group or an exclave does not drag it into the sea.
// It is a label anchor inside the region, not the place of an outage.
//
//   node scripts/gen-ioda-regions.mjs
//
// One request of about 14 MB (gzip). Run it again only if IODA changes its region set.

import { writeFileSync } from "node:fs";

const URL_TOPO = "https://api.ioda.inetintel.cc.gatech.edu/v2/topo/region";
const OUT = new URL("../lib/signals/ioda-regions.data.ts", import.meta.url);

const res = await fetch(URL_TOPO, { headers: { "User-Agent": "Provenance/1.0 (+provenance-online.com)" } });
if (!res.ok) throw new Error(`topo http ${res.status}`);
const body = await res.json();
const topo = body?.data?.topology;
const geoms = topo?.objects?.["ne_10m_admin_1.regions"]?.geometries;
if (!Array.isArray(geoms) || !Array.isArray(topo.arcs)) throw new Error("unexpected topo shape");
if (topo.transform) throw new Error("quantised topology: add the transform decode before using this");

/** One arc as absolute [lon, lat] points; a negative index means the arc reversed. */
function arc(i) {
  const a = topo.arcs[i < 0 ? ~i : i];
  return i < 0 ? [...a].reverse() : a;
}

/** A ring from its arc indices (shared end points appear once). */
function ring(indices) {
  const pts = [];
  for (const i of indices) {
    const a = arc(i);
    pts.push(...(pts.length ? a.slice(1) : a));
  }
  return pts;
}

/** Shoelace area and centroid of a closed ring. */
function ringStats(pts) {
  let a2 = 0, cx = 0, cy = 0;
  for (let k = 0; k < pts.length - 1; k++) {
    const [x0, y0] = pts[k], [x1, y1] = pts[k + 1];
    const f = x0 * y1 - x1 * y0;
    a2 += f;
    cx += (x0 + x1) * f;
    cy += (y0 + y1) * f;
  }
  if (Math.abs(a2) < 1e-12) {
    const n = pts.length || 1;
    return { area: 0, lon: pts.reduce((s, p) => s + p[0], 0) / n, lat: pts.reduce((s, p) => s + p[1], 0) / n };
  }
  return { area: Math.abs(a2 / 2), lon: cx / (3 * a2), lat: cy / (3 * a2) };
}

const rows = [];
for (const g of geoms) {
  const p = g.properties ?? {};
  const id = String(p.id ?? g.id ?? "").trim();
  if (!id || !g.arcs) continue;
  const polys = g.type === "Polygon" ? [g.arcs] : g.type === "MultiPolygon" ? g.arcs : [];
  let best = null;
  for (const poly of polys) {
    const outer = ringStats(ring(poly[0]));
    if (!best || outer.area > best.area) best = outer;
  }
  if (!best) continue;
  const cc = String(p.iso2cc ?? "").toUpperCase();
  const name = String(p.name ?? "").trim();
  if (!name || !/^[A-Z]{2}$/.test(cc)) continue;
  rows.push([Number(id), name, cc, Math.round(best.lat * 100) / 100, Math.round(best.lon * 100) / 100]);
}
rows.sort((a, b) => a[0] - b[0]);

const lines = rows.map(([id, name, cc, lat, lon]) => `  ${id}: [${JSON.stringify(name)}, "${cc}", ${lat}, ${lon}],`);
const src = `// GENERATED by scripts/gen-ioda-regions.mjs from IODA's /v2/topo/region (Natural Earth
// admin-1, public domain, with IODA's region ids). Do not hand-edit: run the script.
//
// IODA region id -> [name, ISO 3166-1 alpha-2, lat, lon]. The coordinate is the
// centroid of the region's largest polygon: an anchor inside the region, not a site.
// ${rows.length} regions.

export type IodaRegionRow = readonly [name: string, iso2: string, lat: number, lon: number];

export const IODA_REGIONS: Readonly<Record<number, IodaRegionRow>> = {
${lines.join("\n")}
};

/** The region row for an IODA location such as "region/1922", or undefined. */
export function iodaRegion(location: string): IodaRegionRow | undefined {
  const m = /^region\\/(\\d+)$/.exec(location.trim());
  return m ? IODA_REGIONS[Number(m[1])] : undefined;
}
`;
writeFileSync(OUT, src);
console.log(`wrote ${rows.length} regions to lib/signals/ioda-regions.data.ts`);
